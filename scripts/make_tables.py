"""Generate the LaTeX table fragments of the paper from results/*.json into tables/."""

import json
import pathlib
import sys
from fractions import Fraction as Fr

ROOT = pathlib.Path(__file__).resolve().parents[1]
RES = ROOT / "results"
OUT = ROOT / "tables"


def load(name):
    return json.loads((RES / f"{name}.json").read_text(encoding="utf8"))


def f(x, nd=3):
    return f"{float(Fr(x)):.{nd}f}"


def table_regimes():
    r = load("regimes")
    lines = ["% generated by scripts/make_tables.py from results/regimes.json"]
    for name, row in r["rows"].items():
        lines.append(f"{name} & {row['q_max']} & {f(row['mu_h'], 2)} & {row['sigma_sqrt_h']:.3f} & {row['dQ']} & "
                     f"{f(row['E_G'])} & {f(row['signed_bound'])} & {f(row['sup_E_G_pos'])} & {row['tail_bound']:.2f} \\\\")
    return "\n".join(lines) + "\n"


def table_channel():
    c = load("channel")
    lines = ["% generated by scripts/make_tables.py from results/channel.json",
             "% q_max & action & E[pi_v] & E[G_v] & C_imm & share via C_imm & L_v & V_v"]
    for row in c["rows"]:
        a = row["action"]
        act = "--" if a is None else f"{'buy' if a[0] > 0 else 'sell'} {a[1]} @ {a[2]}"
        share = "--" if row["share_C"] is None else f"{row['share_C']:.2f}"
        lines.append(f"{row['q_max']} & {act} & {f(row['E_pi'], 2)} & {f(row['E_G'], 2)} & {f(row['C_imm'], 2)} & {share} & "
                     f"{f(row['L_v'], 2)} & {f(row['value_of_victim'], 2)} \\\\")
    return "\n".join(lines) + "\n"


def table_robustness():
    r = load("channel_robustness")
    scales = r["scales"]
    lines = ["% generated by scripts/make_tables.py from results/channel_robustness.json",
             "% book & " + " & ".join(f"tick={s}" for s in scales)]
    for book, d in r["books"].items():
        cells = []
        for s in scales:
            v = d[s]
            sw = "none" if v["switch_cap"] is None else str(v["switch_cap"])
            cells.append(sw)
        lines.append(f"{book} & " + " & ".join(cells) + " \\\\")
    return "\n".join(lines) + "\n"


def table_leakage():
    l = load("leakage")
    lines = ["% generated by scripts/make_tables.py from results/leakage.json",
             f"% signed bound q_max mu_h = {l['signed_bound']}"]
    for name, row in l["rows"].items():
        lines.append(f"{name} & {row['hidden']['dQ']} & {f(row['hidden']['E_G'], 2)} & {row['leaky']['dQ']} & "
                     f"{f(row['leaky']['E_G'], 2)} & {f(row['excess_over_bound'], 2)} \\\\")
    return "\n".join(lines) + "\n"


def table_harm():
    h = load("harm")
    lines = ["% generated by scripts/make_tables.py from results/harm.json",
             "% collar & q_max & E[pi_v] & C_imm & collar bound & L_v & L_v without adversary"]
    for B, sweep in h["collars"].items():
        for row in sweep["rows"]:
            if row["q_max"] not in (1, 4, 10):
                continue
            cb = "--" if row["collar_bound"] is None else f(row["collar_bound"], 0)
            lines.append(f"{B} & {row['q_max']} & {f(row['E_pi'], 2)} & {f(row['C_imm'], 0)} & {cb} & "
                         f"{f(row['L_v'], 0)} & {f(row['L_v_no_adversary'], 0)} \\\\")
    return "\n".join(lines) + "\n"


def table_audit():
    a = load("sequence_audit")
    d = load("differential")
    return ("% generated by scripts/make_tables.py\n"
            f"Books audited & {a['books']} ({a['exhaustive']} exhaustive, {a['sampled']} sampled) \\\\\n"
            f"Permutations tested & {a['permutations']:,} \\\\\n"
            f"Outcome differences & {a['differences']} \\\\\n"
            f"Differential cases (fast vs reference) & {d['cases']:,} \\\\\n"
            f"Mismatches & {d['mismatches']} \\\\\n"
            f"Coupled runs checked against the identity & {d['end_to_end_cases']:,} \\\\\n"
            f"Identity failures & {d['identity_failures']} \\\\\n")


def main():
    OUT.mkdir(exist_ok=True)
    tables = {"table_regimes.tex": table_regimes, "table_channel.tex": table_channel,
              "table_robustness.tex": table_robustness, "table_leakage.tex": table_leakage,
              "table_harm.tex": table_harm, "table_audit.tex": table_audit}
    for name, fn in tables.items():
        try:
            (OUT / name).write_text(fn(), encoding="utf8")
            print("wrote tables/" + name)
        except FileNotFoundError as e:
            print(f"skip {name}: {e}", file=sys.stderr)


if __name__ == "__main__":
    main()
